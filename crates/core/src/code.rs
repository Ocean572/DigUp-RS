//! `CodeExtractor` (CodeExtractor.swift): code for the code index — a source file, a repo's doc
//! or a notebook, cut into stretches of whole lines (a notebook's into whole cells) that the
//! model reads one at a time, each knowing where it is, so that a result opens there.
//!
//! Swift counts CHARACTERS (grapheme clusters), not bytes, everywhere a size is measured: the
//! stretch budget, the 4,000-character cap, the "characters a line" minified test. The port
//! counts the same clusters (`unicode-segmentation`), so a file of accents and emoji cuts in the
//! same places.

use std::path::Path;

use serde_json::Value;
use unicode_segmentation::UnicodeSegmentation;

use crate::extract::ExtractError;
use crate::options::IndexOptions;
use crate::rules;

/// The model reads 2,048 tokens of an input at most; a single line longer than this is cut here.
pub const LONGEST_PIECE: usize = 4000;

/// A stretch of a file: its text, and its first and last lines (or cells), from 1.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Piece {
    pub text: String,
    pub first: i64,
    pub last: i64,
}

/// What reading one code file yields, for the indexer.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct File {
    pub pieces: Vec<Piece>,
    /// The file's title for the model: its path in its repo ("billing/payments/retry.py").
    pub title: String,
    /// The repo (or code project) it's in, if any.
    pub repo: Option<String>,
    pub lines: i64,
    /// A notebook's cells (code and notes; outputs are never read). Nil for anything else.
    pub cells: Option<i64>,
}

/// `CodeExtractor.read(_:options:)`.
pub fn read(path: &Path, options: &IndexOptions) -> Result<File, ExtractError> {
    let data = std::fs::read(path).map_err(|error| ExtractError::Unreadable {
        why: error.to_string(),
    })?;
    let path_text = path.to_string_lossy().to_string();
    let (repo, title) = place(&path_text);
    let extension = extension_of(&path_text).to_lowercase();

    if extension == "ipynb" {
        let cells = notebook_cells(&data)?;
        let text = cells.join("\n");
        // As for any code: more than this was written by a program (data pasted into a cell).
        if text.len() > options.max_code_bytes as usize {
            return Err(ExtractError::LeftOut {
                why: format!("cells over {} MB", options.max_code_bytes >> 20),
            });
        }
        check(&text, true)?;
        return Ok(File {
            pieces: notebook_pieces(&cells, options.code_stretch),
            title,
            repo,
            lines: line_count(&text),
            cells: Some(cells.len() as i64),
        });
    }

    if data.iter().take(8000).any(|byte| *byte == 0) {
        return Err(ExtractError::LeftOut {
            why: "not text".into(),
        });
    }
    // Swift's read: strict UTF-8, else ISO-Latin-1 (every byte a character), else nothing.
    let text = String::from_utf8(data.clone())
        .unwrap_or_else(|_| data.iter().map(|byte| char::from(*byte)).collect());
    check(
        &text,
        rules::SOURCE_EXTENSIONS.contains(&extension.as_str()),
    )?;
    Ok(File {
        pieces: lines(&text, options.code_stretch),
        title,
        repo,
        lines: line_count(&text),
        cells: None,
    })
}

/// Code that's no use to read: it holds a private key, or (`source`: code, not a repo's notes) a
/// program wrote it (its generator says so at the top: "DO NOT EDIT", "@generated") or it's minified.
pub fn check(text: &str, source: bool) -> Result<(), ExtractError> {
    if text.contains("PRIVATE KEY-----") {
        return Err(ExtractError::LeftOut {
            why: "holds a private key".into(),
        });
    }
    if !source {
        return Ok(());
    }
    let top: String = text.graphemes(true).take(1000).collect();
    for mark in [
        "DO NOT EDIT",
        "@generated",
        "Code generated by",
        "Autogenerated by",
        "Generated by the protocol",
    ] {
        if top.contains(mark) {
            return Err(ExtractError::LeftOut {
                why: format!("made by a program (“{mark}”)"),
            });
        }
    }
    // Minified: few lines, and long ones (a bundle can be one line of 100,000 characters).
    let lines = line_count(text).max(1);
    let characters = text.graphemes(true).count() as i64;
    let over_3000 = split_newline_chars(text)
        .iter()
        .any(|line| graphemes(line) > 3000);
    if characters / lines > 300 && over_3000 {
        return Err(ExtractError::LeftOut {
            why: format!("minified ({} characters a line)", characters / lines),
        });
    }
    Ok(())
}

/// `CodeExtractor.lineCount`: newlines, counting the last line when the text has no final one.
/// Swift's `hasSuffix("\n")` compares CHARACTERS, and CR-LF is one Character — a CRLF file's last
/// Character is `"\r\n"`, not `"\n"`, so it counts one line more. The grapheme rules Rust counts by
/// are the same ones Swift's `Character` follows (UAX #29), so this asks the last cluster.
pub fn line_count(text: &str) -> i64 {
    let count = text.bytes().filter(|byte| *byte == 0x0A).count() as i64;
    if text.is_empty() {
        return count;
    }
    let ends_with_newline = text.graphemes(true).next_back() == Some("\n");
    if ends_with_newline {
        count
    } else {
        count + 1
    }
}

/// Swift's `split(omittingEmptySubsequences:whereSeparator:)` with the separators "\n" and
/// "\r\n", tried longest first; a lone "\r" is ordinary text.
fn split_lines(text: &str, drop_trailing_empty: bool) -> Vec<String> {
    let mut lines: Vec<String> = Vec::new();
    let mut current = String::new();
    let bytes: Vec<char> = text.chars().collect();
    let mut index = 0usize;
    while index < bytes.len() {
        if bytes[index] == '\r' && index + 1 < bytes.len() && bytes[index + 1] == '\n' {
            lines.push(std::mem::take(&mut current));
            index += 2;
        } else if bytes[index] == '\n' {
            lines.push(std::mem::take(&mut current));
            index += 1;
        } else {
            current.push(bytes[index]);
            index += 1;
        }
    }
    lines.push(current);
    if drop_trailing_empty && lines.last().map(|line| line.is_empty()) == Some(true) {
        lines.pop(); // the final newline
    }
    lines
}

fn graphemes(text: &str) -> usize {
    text.graphemes(true).count()
}

/// Swift's `split(separator: "\n")` over CHARACTERS: CR-LF is a single Character and is not the
/// separator, so a CRLF file stays one long line. Empty pieces drop, as Swift's `split` drops them.
fn split_newline_chars(text: &str) -> Vec<String> {
    let mut parts: Vec<String> = Vec::new();
    let mut current = String::new();
    for cluster in text.graphemes(true) {
        if cluster == "\n" {
            if !current.is_empty() {
                parts.push(std::mem::take(&mut current));
            }
        } else {
            current.push_str(cluster);
        }
    }
    if !current.is_empty() {
        parts.push(current);
    }
    parts
}

fn grapheme_prefix(text: &str, count: usize) -> String {
    text.graphemes(true).take(count).collect()
}

fn grapheme_trim(text: &str) -> String {
    text.trim().to_string()
}

/// Lines that close a block (shell, Ruby, Lua, Objective-C, the C preprocessor).
const CLOSERS: [&str; 8] = [
    "end", "fi", "done", "esac", "@end", "#endif", "end;", "end)",
];

/// Stretches of whole lines, each at most `size` characters (a longer line is a stretch of its
/// own). A stretch ends, when it can, where the code does: before a line that starts a new block
/// at the left margin, or after a blank line, in its last 60%. One that had to stop in the middle
/// of a block hands its last two lines on to the next, so whatever spans the cut is read whole once.
pub fn lines(text: &str, size: i64) -> Vec<Piece> {
    let lines = split_lines(text, true);
    let count = lines.len();
    // Characters before each line (each with its newline), as the engine counts them: `+ 1` per line.
    let mut offsets: Vec<i64> = vec![0];
    for line in &lines {
        offsets.push(*offsets.last().unwrap() + graphemes(line) as i64 + 1);
    }
    let blank = |index: usize| lines[index].chars().all(char::is_whitespace);
    let starts_block = |index: usize| -> bool {
        let line = lines[index].as_str();
        let first = match grapheme_first(line) {
            None => return false,
            Some(ch) => ch,
        };
        if first.is_whitespace() {
            return false;
        }
        // A closing line belongs to the block above it.
        let trimmed = grapheme_trim(line);
        !"})]".contains(first) && !CLOSERS.contains(&trimmed.as_str())
    };

    let mut pieces: Vec<Piece> = Vec::new();
    let mut start = 0usize;
    while start < count {
        while start < count && blank(start) {
            start += 1;
        }
        if start >= count {
            break;
        }
        let mut end = start + 1; // the stretch is lines[start..end]
        while end < count && offsets[end + 1] - offsets[start] <= size {
            end += 1;
        }
        let mut natural = end >= count;
        if !natural {
            // Where the code breaks by itself, keeping at least 40% of a stretch: a new block after a
            // blank line first, then any blank line or new block.
            let floor = offsets[start] + size * 2 / 5;
            let last_break = |is_break: &dyn Fn(usize) -> bool| -> Option<usize> {
                let mut line = end;
                while line > start + 1 && offsets[line] >= floor {
                    if is_break(line) {
                        return Some(line);
                    }
                    line -= 1;
                }
                None
            };
            let cut = last_break(&|line| starts_block(line) && blank(line - 1))
                .or_else(|| last_break(&|line| blank(line - 1) || starts_block(line)));
            if let Some(cut) = cut {
                end = cut;
                natural = true;
            }
        }
        let mut last = end;
        while last > start + 1 && blank(last - 1) {
            last -= 1; // blank lines at its end don't count
        }
        let mut body = lines[start..last].join("\n");
        if graphemes(&body) > LONGEST_PIECE {
            body = grapheme_prefix(&body, LONGEST_PIECE);
        }
        pieces.push(Piece {
            text: body,
            first: start as i64 + 1,
            last: last as i64,
        });
        // Swift's `max(end - 2, start + 1)` is signed; a single-line stretch (end == start + 1)
        // must not wrap the way unsigned `end - 2` would.
        start = if natural {
            end
        } else {
            (end as i64 - 2).max(start as i64 + 1) as usize
        };
    }
    pieces
}

fn grapheme_first(text: &str) -> Option<char> {
    text.graphemes(true)
        .next()
        .and_then(|cluster| cluster.chars().next())
}

/// A stretch in one line, for result lists: its first line that defines something
/// ("def retry_with_backoff(…"), else its first line of code (not a comment, an import or a
/// closing brace).
pub fn summary(text: &str) -> String {
    let lines: Vec<String> = split_lines(text, false)
        .into_iter()
        .map(|line| grapheme_trim(&line))
        .filter(|line| !line.is_empty())
        .collect();
    let definition = lines
        .iter()
        .find(|line| line.split_whitespace().take(4).any(defines_something));
    let code = lines.iter().find(|line| {
        ![
            "//", "#", "/*", "*", "--", "\"\"\"", "import ", "from ", "#include", "using ",
            "package ", "}", ")", "@",
        ]
        .iter()
        .any(|prefix| line.starts_with(prefix))
    });
    let line = definition
        .or(code)
        .or(lines.first())
        .cloned()
        .unwrap_or_default();
    if graphemes(&line) > 160 {
        grapheme_prefix(&line, 160) + "…"
    } else {
        line
    }
}

/// A word that starts a definition ("def", "func", "class", "@implementation"…), of the ones that
/// define something: `CodeLookup.definesSomething` minus the bare declarations.
pub fn defines_something(word: &str) -> bool {
    DEFINERS.contains(&word) && word != "let" && word != "var" && word != "const" && word != "val"
}

