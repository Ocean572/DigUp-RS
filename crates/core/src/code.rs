// MARK: Notebooks

/// The cells of a Jupyter notebook, code and notes alike, as their text. Outputs (pictures,
/// tables, logs) aren't read: they're results, not what anyone wrote.
pub fn notebook_cells(data: &[u8]) -> Result<Vec<String>, ExtractError> {
    let notebook: Value = match serde_json::from_slice(data) {
        Ok(Value::Object(fields)) => Value::Object(fields),
        _ => {
            return Err(ExtractError::Unreadable {
                why: "not a notebook".into(),
            })
        }
    };
    // nbformat 4 keeps its cells at the top; nbformat 3 inside worksheets, with code in "input".
    let as_array = |value: Option<&Value>| -> Option<Vec<Value>> {
        value.and_then(|value| value.as_array()).cloned()
    };
    let worksheets = as_array(notebook.get("worksheets"));
    let cells: Vec<Value> = as_array(notebook.get("cells"))
        .or_else(|| {
            worksheets
                .and_then(|sheets| sheets.into_iter().next())
                .and_then(|sheet| sheet.get("cells").cloned())
                .and_then(|cells| cells.as_array().cloned())
        })
        .unwrap_or_default();
    Ok(cells
        .iter()
        .map(|cell| {
            let source = cell.get("source").or_else(|| cell.get("input"));
            match source {
                // `joined()` of strings: concatenated, with no separator. Any non-string in the
                // array fails Swift's `[String]` cast, which lands on "" as this does.
                Some(Value::Array(lines)) if lines.iter().all(Value::is_string) => lines
                    .iter()
                    .map(Value::as_str)
                    .collect::<Option<Vec<&str>>>()
                    .map(|lines| lines.concat())
                    .unwrap_or_default(),
                Some(Value::String(text)) => text.clone(),
                _ => String::new(),
            }
        })
        .collect())
}

/// Whole cells to a stretch, up to `size` characters; a longer cell is cut into stretches of lines
/// that all point at it. Empty cells are passed over.
pub fn notebook_pieces(cells: &[String], size: i64) -> Vec<Piece> {
    let mut pieces: Vec<Piece> = Vec::new();
    let mut text = String::new();
    let mut first = 0i64;
    let mut last = 0i64;
    macro_rules! flush {
        () => {
            if !text.is_empty() {
                pieces.push(Piece {
                    text: std::mem::take(&mut text),
                    first,
                    last,
                });
            }
        };
    }
    for (index, cell) in cells.iter().enumerate() {
        let body = cell.trim().to_string();
        if body.is_empty() {
            continue;
        }
        let number = index as i64 + 1;
        if graphemes(&body) as i64 > size {
            flush!();
            pieces.extend(lines(&body, size).into_iter().map(|piece| Piece {
                text: piece.text,
                first: number,
                last: number,
            }));
            continue;
        }
        if !text.is_empty() && graphemes(&text) as i64 + 2 + graphemes(&body) as i64 > size {
            flush!();
        }
        if text.is_empty() {
            first = number;
            text = body;
        } else {
            text.push_str("\n\n");
            text.push_str(&body);
        }
        last = number;
    }
    flush!();
    pieces
}

// MARK: Where it is

/// The repo (or code project) `path` is in, and the file's title: its path from the repo's folder,
/// the repo's name first. Outside any: its folder's name and its own.
pub fn place(path: &str) -> (Option<String>, String) {
    let home = home_folder();
    let mut folder = parent_of(path);
    let mut repo: Option<String> = None;
    while folder.chars().count() > 1 && folder != home {
        if Path::new(&folder).join(".git").exists() || rules::is_project_root(&folder) {
            repo = Some(folder.clone());
            break;
        }
        folder = parent_of(&folder);
    }
    if let Some(repo) = repo {
        let parent = parent_of(&repo);
        let skip = parent.chars().count() + 1;
        return (Some(repo), path.chars().skip(skip).collect::<String>());
    }
    let components = path_components(path);
    let tail = if components.len() >= 2 {
        &components[components.len() - 2..]
    } else {
        &components[..]
    };
    (None, tail.join("/"))
}

/// `FileManager.default.homeDirectoryForCurrentUser.path`. Foundation reads it from the password
/// entry; HOME is what the login sets from the same entry, and is what the engine's own helpers see.
fn home_folder() -> String {
    std::env::var("HOME").unwrap_or_default()
}

fn parent_of(path: &str) -> String {
    let trimmed = path.trim_end_matches('/');
    match trimmed.rfind('/') {
        Some(0) => "/".to_string(),
        Some(index) => trimmed[..index].to_string(),
        None => String::new(),
    }
}

/// `NSString.pathComponents`: the leading "/" kept, "." dropped, repeats of "/" collapsed.
fn path_components(path: &str) -> Vec<String> {
    let mut parts: Vec<String> = Vec::new();
    if path.starts_with('/') {
        parts.push("/".to_string());
    }
    for piece in path.split('/') {
        if piece.is_empty() || piece == "." {
            continue;
        }
        parts.push(piece.to_string());
    }
    parts
}

fn extension_of(path: &str) -> String {
    let name = path.rsplit('/').next().unwrap_or(path);
    match name.rfind('.') {
        Some(index) if index > 0 => name[index + 1..].to_string(),
        _ => String::new(),
    }
}

/// "Swift", "Python", "Markdown": what a file's extension says it's written in.
pub fn language_of(path: &str) -> String {
    let name = path.rsplit('/').next().unwrap_or(path);
    let ext = extension_of(name).to_lowercase();
    if let Some(language) = LANGUAGES.get(ext.as_str()) {
        return language.to_string();
    }
    if rules::CODE_FILE_NAMES.contains(&name) || name.starts_with("Dockerfile") {
        return name.to_string();
    }
    if ext.is_empty() {
        "Text".to_string()
    } else {
        ext.to_uppercase()
    }
}

